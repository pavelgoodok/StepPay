def n(v, d=1):
    s = f"{v:,.{d}f}".replace(",", " ").replace(".", ",")
    return s.replace("-", "минус ") if False else s


def pct(v, d=1):
    return n(v * 100, d) + " %"


def bln(v):  # тыс. руб. -> млрд руб.
    return n(v / 1e6, 1)


