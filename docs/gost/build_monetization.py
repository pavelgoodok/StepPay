    D.p("Документ описывает, как проект StepPay получает выручку, сколько платят участники и почему заказчику выгодно пользоваться сервисом. Расчеты согласованы с документом об анализе рынка: средний чек сделки 50 000 руб., комиссия 1,5 %, достижимый объем на третий год 2 000 сделок в месяц. Значения тарифов и объемов являются плановыми и уточняются на пилоте.")
